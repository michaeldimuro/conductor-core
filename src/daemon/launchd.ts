import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { chmodSync, existsSync, mkdirSync, readlinkSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { homedir, userInfo } from 'node:os';
import { dirname, join } from 'node:path';

const exec = promisify(execFile);

export const LABEL = 'ai.conductor.daemon';
export const SYSTEM_BIN = '/usr/local/bin/conductord';

export interface PlistOptions {
  /** Absolute path of the conductord executable. */
  program: string;
  logDir: string;
  /** Extra environment for the daemon (PATH, CONDUCTOR_HOME…). */
  env: Record<string, string>;
  /** LaunchDaemon variant: boot without login, headless profile (no Keychain; file vault). */
  headless?: { userName: string };
  label?: string;
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/**
 * launchd property list for the daemon (PRD "Auto-start with launchd"):
 * RunAtLoad=true, KeepAlive={SuccessfulExit:false}, ThrottleInterval=10,
 * stdout/stderr to ~/Library/Logs/Conductor/.
 */
export function renderPlist(o: PlistOptions): string {
  const env = Object.entries(o.env)
    .map(([k, v]) => `    <key>${esc(k)}</key><string>${esc(v)}</string>`)
    .join('\n');
  const headless = o.headless
    ? `  <key>UserName</key><string>${esc(o.headless.userName)}</string>\n`
    : '  <key>ProcessType</key><string>Interactive</string>\n';
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${esc(o.label ?? LABEL)}</string>
  <key>ProgramArguments</key><array><string>${esc(o.program)}</string><string>--serve</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>ThrottleInterval</key><integer>10</integer>
  <key>StandardOutPath</key><string>${esc(join(o.logDir, 'conductord.out.log'))}</string>
  <key>StandardErrorPath</key><string>${esc(join(o.logDir, 'conductord.err.log'))}</string>
  <key>WorkingDirectory</key><string>${esc(o.env.CONDUCTOR_HOME ?? homedir())}</string>
${headless}  <key>EnvironmentVariables</key>
  <dict>
${env}
  </dict>
</dict>
</plist>
`;
}

export function launchAgentPath(label = LABEL): string {
  return join(homedir(), 'Library', 'LaunchAgents', `${label}.plist`);
}

/** Shell wrapper so launchd (which has a minimal PATH) always finds this node and this build. */
export function renderWrapper(nodePath: string, entry: string): string {
  return `#!/bin/sh\n# Generated by \`conductor install\`. Do not edit.\nexec "${nodePath}" "${entry}" "$@"\n`;
}

export interface InstallOptions {
  /** Conductor home (default ~/.conductor). */
  home: string;
  /** Absolute path of the daemon entry script (dist/daemon/main.js). */
  entry: string;
  nodePath?: string;
  logDir?: string;
  port?: number;
  /** Write the plist but do not call launchctl (tests, dry runs). */
  load?: boolean;
  label?: string;
  plistPath?: string;
  /** Try to link /usr/local/bin/conductord (skipped silently when not writable). */
  systemLink?: boolean;
}

export interface InstallResult {
  plistPath: string;
  program: string;
  wrapper: string;
  logDir: string;
  loaded: boolean;
  linkedSystemBin: boolean;
}

/**
 * Install the LaunchAgent. A LaunchAgent (not a LaunchDaemon) is required
 * because agents need the logged-in user's Keychain, browser and GUI session.
 */
export async function installLaunchAgent(o: InstallOptions): Promise<InstallResult> {
  const nodePath = o.nodePath ?? process.execPath;
  const label = o.label ?? LABEL;
  const logDir = o.logDir ?? join(homedir(), 'Library', 'Logs', 'Conductor');
  const plistPath = o.plistPath ?? launchAgentPath(label);

  mkdirSync(logDir, { recursive: true });
  mkdirSync(join(o.home, 'bin'), { recursive: true });
  const wrapper = join(o.home, 'bin', 'conductord');
  writeFileSync(wrapper, renderWrapper(nodePath, o.entry), { mode: 0o755 });
  chmodSync(wrapper, 0o755);

  // Prefer the PRD's /usr/local/bin/conductord when we can link it without sudo.
  let program = wrapper;
  let linkedSystemBin = false;
  if (o.systemLink !== false) {
    try {
      if (existsSync(SYSTEM_BIN) && readlinkSync(SYSTEM_BIN) !== wrapper) rmSync(SYSTEM_BIN);
      if (!existsSync(SYSTEM_BIN)) symlinkSync(wrapper, SYSTEM_BIN);
      program = SYSTEM_BIN;
      linkedSystemBin = true;
    } catch {
      /* /usr/local/bin not writable without sudo — the wrapper path works just as well */
    }
  }

  const path = [dirname(nodePath), join(homedir(), '.local', 'bin'), '/opt/homebrew/bin', '/usr/local/bin', '/usr/bin', '/bin', '/usr/sbin', '/sbin'];
  const env: Record<string, string> = {
    PATH: [...new Set(path)].join(':'),
    HOME: homedir(),
    CONDUCTOR_HOME: o.home,
    CONDUCTOR_LOG_DIR: logDir,
    ...(o.port ? { CONDUCTOR_PORT: String(o.port) } : {}),
  };

  mkdirSync(dirname(plistPath), { recursive: true });
  writeFileSync(plistPath, renderPlist({ program, logDir, env, label }), { mode: 0o644 });

  let loaded = false;
  if (o.load !== false) {
    const domain = `gui/${userInfo().uid}`;
    await exec('/bin/launchctl', ['bootout', `${domain}/${label}`]).catch(() => {});
    await exec('/bin/launchctl', ['bootstrap', domain, plistPath]);
    await exec('/bin/launchctl', ['enable', `${domain}/${label}`]).catch(() => {});
    loaded = true;
  }
  return { plistPath, program, wrapper, logDir, loaded, linkedSystemBin };
}

export async function uninstallLaunchAgent(label = LABEL, plistPath = launchAgentPath(label)): Promise<void> {
  await exec('/bin/launchctl', ['bootout', `gui/${userInfo().uid}/${label}`]).catch(() => {});
  rmSync(plistPath, { force: true });
}

export interface LaunchdStatus {
  installed: boolean;
  loaded: boolean;
  pid: number | null;
  lastExitCode: number | null;
  plistPath: string;
}

export async function launchdStatus(label = LABEL, plistPath = launchAgentPath(label)): Promise<LaunchdStatus> {
  const status: LaunchdStatus = { installed: existsSync(plistPath), loaded: false, pid: null, lastExitCode: null, plistPath };
  try {
    const { stdout } = await exec('/bin/launchctl', ['print', `gui/${userInfo().uid}/${label}`]);
    status.loaded = true;
    const pid = /^\s*pid = (\d+)/m.exec(stdout);
    const exit = /^\s*last exit code = (-?\d+)/m.exec(stdout);
    status.pid = pid ? Number(pid[1]) : null;
    status.lastExitCode = exit ? Number(exit[1]) : null;
  } catch {
    /* not loaded */
  }
  return status;
}

export async function restartLaunchAgent(label = LABEL): Promise<void> {
  await exec('/bin/launchctl', ['kickstart', '-k', `gui/${userInfo().uid}/${label}`]);
}

/**
 * Advanced: the LaunchDaemon variant for true boot-without-login. Runs a
 * headless profile — no Keychain (secrets come from the encrypted file vault,
 * CONDUCTOR_SECRETS=vault) and no GUI browser session. Returned as text for the
 * operator to install with sudo into /Library/LaunchDaemons; never auto-installed.
 */
export function renderHeadlessDaemonPlist(o: { program: string; home: string; logDir: string; userName?: string; vaultKeyFile: string }): string {
  return renderPlist({
    program: o.program,
    logDir: o.logDir,
    label: `${LABEL}.headless`,
    headless: { userName: o.userName ?? userInfo().username },
    env: {
      PATH: `${dirname(process.execPath)}:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin`,
      HOME: homedir(),
      CONDUCTOR_HOME: o.home,
      CONDUCTOR_LOG_DIR: o.logDir,
      CONDUCTOR_SECRETS: 'vault',
      CONDUCTOR_VAULT_KEY_FILE: o.vaultKeyFile,
      CONDUCTOR_HEADLESS: '1',
    },
  });
}
